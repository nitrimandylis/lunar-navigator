"""Render a grey hillshade of the lunar south pole for the app map.

    python data/basemap.py --dem5 <5 m DEM .tif> --dem30 <30 m DEM .tif> --out public/data

Writes basemap.png / basemap.json (30 m DEM, out to latitude -82) and basemap-87.5.png /
basemap-87.5.json (5 m DEM, out to latitude -87.5). The picture uses the SAME projection as
the app's south pole map (lib/geometry.ts projectSouthPole): azimuthal equidistant, so the
distance from the centre is proportional to degrees from the pole; longitude 0 straight up;
east longitude clockwise (lon 90 to the right). A pin at (lat, lon) lands on the pixel given
by latlon_to_pixel().

The DEMs (LRO LOLA DEM v4 S Pole, NASA Moon Trek) are polar stereographic, so every output
pixel is looked up in the DEM through terrain.lonlat_to_xy. The DEMs are never read whole: the
needed window is read with averaging down to about one output pixel.
"""

from __future__ import annotations

import argparse
import json
import math
import struct
import zlib
from pathlib import Path

import numpy as np
import rasterio
from rasterio.enums import Resampling
from rasterio.windows import Window

import terrain
from horizon_mask import MOON_RADIUS_M

# Hillshade settings. The Sun at the pole never gets above about 1.5 degrees, so a real
# light would leave everything black; a made-up light 20 degrees up, with the heights
# stretched 2x, makes crater walls and rims readable. Azimuth is in the picture: degrees
# clockwise from "up the image" (lon 0), so 315 is the upper left.
LIGHT_AZIMUTH_DEG = 315.0
LIGHT_ELEVATION_DEG = 20.0
VERTICAL_EXAGGERATION = 2.0

DEFAULT_SIZE = 2048
GENERATED_BY = "generated by data/basemap.py"
DEM_PRODUCT = "LRO LOLA DEM v4 S Pole, NASA Moon Trek"

# The two tiles: file stem, outer latitude, which DEM, JSON key for the DEM.
TILES = [
    {"stem": "basemap", "edge_lat": -82.0, "dem": "dem30", "dem_name": "LRO_LOLA_DEM_SPole75_30mp_v04.tif", "dem_res_m": 30},
    {"stem": "basemap-87.5", "edge_lat": -87.5, "dem": "dem5", "dem_name": "LRO_LOLA_DEM_SPole875_5mp_v04.tif", "dem_res_m": 5},
]


# ---- projection (same maths as lib/geometry.ts projectSouthPole, in pixels) ----


def latlon_to_pixel(lat_deg: float, lon_deg: float, size: int, edge_lat_deg: float) -> tuple[float, float]:
    """(lat, east lon) to image position (x right, y down) in pixel units.

    Pixel edges are on whole numbers, so the pole is at (size/2, size/2) and the centre of the
    top-left pixel is (0.5, 0.5). Latitude edge_lat_deg is at radius size/2 (the middle of each side).
    """
    half = size / 2.0
    r = half * (lat_deg + 90.0) / (edge_lat_deg + 90.0)
    lon = math.radians(lon_deg)
    return half + r * math.sin(lon), half - r * math.cos(lon)


def pixel_to_latlon(x: float, y: float, size: int, edge_lat_deg: float) -> tuple[float, float]:
    """Inverse of latlon_to_pixel. Longitude comes back in -180..180 (east positive)."""
    half = size / 2.0
    dx, dy = x - half, half - y
    r = math.hypot(dx, dy)
    lat = -90.0 + r / half * (edge_lat_deg + 90.0)
    return lat, math.degrees(math.atan2(dx, dy))


def pixel_grid_latlon(size: int, edge_lat_deg: float) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Colatitude (radians), east longitude (radians) and an inside-the-edge-circle mask,
    for the centre of every pixel."""
    half = size / 2.0
    idx = np.arange(size) + 0.5
    dx = (idx - half)[None, :] * np.ones((size, 1))
    dy = (half - idx)[:, None] * np.ones((1, size))
    r = np.hypot(dx, dy)
    colat = r / half * math.radians(90.0 + edge_lat_deg)
    lon = np.arctan2(dx, dy)
    return colat, lon, r <= half


def colat_to_dem_xy(colat: np.ndarray, lon: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Vector version of terrain.lonlat_to_xy: polar stereographic metres (x east, y up)."""
    rho = 2.0 * MOON_RADIUS_M * np.tan(colat / 2.0)
    return rho * np.sin(lon), rho * np.cos(lon)


def edge_extent_m(edge_lat_deg: float) -> float:
    """Distance along the ground from the pole to the edge circle, metres (azimuthal equidistant)."""
    return MOON_RADIUS_M * math.radians(90.0 + edge_lat_deg)


def pixel_size_m(size: int, edge_lat_deg: float) -> float:
    """Ground metres per pixel along a radius."""
    return 2.0 * edge_extent_m(edge_lat_deg) / size


# ---- reading the DEM ----


def read_pole_window(dem_path: str, edge_lat_deg: float, target_m: float) -> tuple[np.ndarray, float, float]:
    """Read the square of the DEM around the pole that holds the edge circle, averaged down to
    about target_m per pixel. Returns (heights in metres with nan for no data, cell size in
    metres, half width in metres). The window is centred on the pole and a whole number of
    cells wide, so the pole sits on a cell corner."""
    rho_edge = 2.0 * MOON_RADIUS_M * math.tan(math.radians(90.0 + edge_lat_deg) / 2.0)
    with rasterio.open(dem_path) as dem:
        res = dem.res[0]
        cx = (0.0 - dem.transform.c) / res  # column of the pole (cell corner coordinates)
        cy = (dem.transform.f - 0.0) / res
        factor = max(1, int(round(target_m / res)))
        want = int(math.ceil((rho_edge / res + 3 * factor) / factor)) * factor
        have = int(min(cx, cy, dem.width - cx, dem.height - cy) // factor) * factor
        half = min(want, have)
        window = Window(int(round(cx)) - half, int(round(cy)) - half, 2 * half, 2 * half)
        n = 2 * half // factor
        data = dem.read(1, window=window, out_shape=(n, n), resampling=Resampling.average).astype(np.float64)
        nodata = dem.nodata
    bad = ~np.isfinite(data)
    if nodata is not None:
        bad |= data <= nodata * 0.5 if nodata < 0 else data == nodata
    data[bad] = np.nan
    return data, res * factor, half * res


def sample_bilinear(grid: np.ndarray, col: np.ndarray, row: np.ndarray) -> np.ndarray:
    """Bilinear lookup at fractional positions; col/row are in cell units with a cell centre at +0.5.
    Positions outside the grid are clamped to its edge."""
    h, w = grid.shape
    c = np.clip(col - 0.5, 0.0, w - 1.000001)
    r = np.clip(row - 0.5, 0.0, h - 1.000001)
    c0 = np.floor(c).astype(int)
    r0 = np.floor(r).astype(int)
    fc = c - c0
    fr = r - r0
    top = grid[r0, c0] * (1 - fc) + grid[r0, c0 + 1] * fc
    bottom = grid[r0 + 1, c0] * (1 - fc) + grid[r0 + 1, c0 + 1] * fc
    return top * (1 - fr) + bottom * fr


def resample_to_pole_grid(dem_path: str, size: int, edge_lat_deg: float) -> np.ndarray:
    """Heights (metres) on the output grid: heights[row, col] for the pixel centre; nan outside the circle."""
    cell_m = pixel_size_m(size, edge_lat_deg)
    grid, cell, half_m = read_pole_window(dem_path, edge_lat_deg, cell_m)
    colat, lon, inside = pixel_grid_latlon(size, edge_lat_deg)
    x, y = colat_to_dem_xy(colat, lon)
    col = (x + half_m) / cell
    row = (half_m - y) / cell
    # nan holes: fill with the mean so the filter does not spread nan; tiles seldom have any.
    if np.isnan(grid).any():
        grid = np.where(np.isnan(grid), np.nanmean(grid), grid)
    out = sample_bilinear(grid, col, row)
    out[~inside] = np.nan
    return out


# ---- shading ----


def hillshade(
    heights: np.ndarray,
    cell_m: float,
    azimuth_deg: float = LIGHT_AZIMUTH_DEG,
    elevation_deg: float = LIGHT_ELEVATION_DEG,
    exaggeration: float = VERTICAL_EXAGGERATION,
) -> np.ndarray:
    """Hillshade in 0..1 of a height grid (rows go down, cells cell_m metres across).

    The light comes from azimuth_deg, clockwise from the top of the image. Flat ground gets
    sin(elevation_deg). Cells with a nan neighbour take the flat value."""
    z = np.asarray(heights, dtype=np.float64) * exaggeration
    # slope towards the right (east in the picture) and towards the top (north in the picture)
    dz_dx = np.gradient(z, cell_m, axis=1)
    dz_dn = -np.gradient(z, cell_m, axis=0)
    az = math.radians(azimuth_deg)
    el = math.radians(elevation_deg)
    lx, ln, lz = math.sin(az) * math.cos(el), math.cos(az) * math.cos(el), math.sin(el)
    shade = (-dz_dx * lx - dz_dn * ln + lz) / np.sqrt(dz_dx**2 + dz_dn**2 + 1.0)
    shade = np.clip(shade, 0.0, 1.0)
    return np.where(np.isfinite(shade), shade, math.sin(el))


def to_gray_alpha(shade: np.ndarray, inside: np.ndarray) -> np.ndarray:
    """8-bit grey plus alpha, shape (rows, cols, 2). Outside the edge circle: grey 0, alpha 0."""
    grey = np.clip(np.rint(shade * 255.0), 0, 255).astype(np.uint8)
    grey[~inside] = 0
    alpha = np.where(inside, 255, 0).astype(np.uint8)
    return np.stack([grey, alpha], axis=-1)


# ---- PNG writing (standard library only) ----


def _chunk(kind: bytes, payload: bytes) -> bytes:
    body = kind + payload
    return struct.pack(">I", len(payload)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)


def encode_png_gray_alpha(img: np.ndarray) -> bytes:
    """PNG bytes for a (rows, cols, 2) uint8 array: 8-bit greyscale with alpha, Sub filter."""
    rows, cols, _ = img.shape
    flat = img.reshape(rows, cols * 2).astype(np.int16)
    sub = flat.copy()
    sub[:, 2:] = (flat[:, 2:] - flat[:, :-2]) % 256
    raw = np.concatenate([np.ones((rows, 1), dtype=np.int16), sub], axis=1).astype(np.uint8)
    ihdr = struct.pack(">IIBBBBB", cols, rows, 8, 4, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + _chunk(b"IHDR", ihdr)
        + _chunk(b"IDAT", zlib.compress(raw.tobytes(), 9))
        + _chunk(b"IEND", b"")
    )


def png_size(data: bytes) -> tuple[int, int]:
    """(width, height) read from the IHDR chunk of PNG bytes."""
    if data[:8] != b"\x89PNG\r\n\x1a\n" or data[12:16] != b"IHDR":
        raise ValueError("not a PNG")
    return struct.unpack(">II", data[16:24])


