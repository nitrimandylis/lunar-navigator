def render_tile(dem_path: str, edge_lat_deg: float, size: int) -> tuple[np.ndarray, tuple[float, float]]:
    heights = resample_to_pole_grid(dem_path, size, edge_lat_deg)
    inside = np.isfinite(heights)
    filled = np.where(inside, heights, np.nanmean(heights))
    shade = hillshade(filled, pixel_size_m(size, edge_lat_deg))
    return to_gray_alpha(shade, inside), (float(np.nanmin(heights)), float(np.nanmax(heights)))


def main() -> None:
    here = Path(__file__).resolve().parent
    p = argparse.ArgumentParser()
    p.add_argument("--dem5", default=str(here / "raw/LRO_LOLA_DEM_SPole875_5mp_v04.tif"))
    p.add_argument("--dem30", default=str(here / "raw/LRO_LOLA_DEM_SPole75_30mp_v04.tif"))
    p.add_argument("--out", default=str(here.parent / "public/data"))
    p.add_argument("--size", type=int, default=DEFAULT_SIZE, help="pixels across (square)")
    p.add_argument("--only", help="render just this tile, e.g. basemap or basemap-87.5")
    args = p.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for tile in TILES:
        if args.only and args.only != tile["stem"]:
            continue
        dem_path = getattr(args, tile["dem"])
        img, hrange = render_tile(dem_path, tile["edge_lat"], args.size)
        png = encode_png_gray_alpha(img)
        (out / f"{tile['stem']}.png").write_bytes(png)
        info = tile_json(tile["stem"], tile["edge_lat"], args.size, tile["dem_name"], tile["dem_res_m"], hrange)
        (out / f"{tile['stem']}.json").write_text(json.dumps(info, indent=2) + "\n")
        print(f"{tile['stem']}: {len(png) / 1e6:.2f} MB, heights {hrange[0]:.0f}..{hrange[1]:.0f} m")


if __name__ == "__main__":
    main()
